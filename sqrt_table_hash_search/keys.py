#!/usr/bin/env python3
"""Keys of the square-root inverse table of bls12_381's Scalar (see src/sqrt_table.rs).

SqrtTables::new hashes the 256 elements ROOT_OF_UNITY^(2^24 * j), j = 0..255 (the order-256
subgroup), by the low 32 bits of their normalized Montgomery representation
(`Scalar::sqrt_hash_key`, `self.0[0] as u32`).

    python3 keys.py            # print the keys as a C header (input of search.c)
    python3 keys.py 0x60FF5F7B # check that a multiplier is a perfect hash at SQRT_HASH_BITS = 10
"""
import sys

Q = 0x73EDA753299D7D483339D80809A1D80553BDA402FFFE5BFEFFFFFFFF00000001
R = pow(2, 256, Q)
R_INV = pow(R, Q - 2, Q)
# ROOT_OF_UNITY in Montgomery form, as in src/scalar.rs.
ROOT_OF_UNITY_MONT = [0xB9B58D8C5F0E466A, 0x5B1B4C801819D7EC, 0x0AF53AE352A31E64, 0x5BF3ADDA19E9B27B]
SQRT_HASH_BITS = 10

root = sum(l << (64 * i) for i, l in enumerate(ROOT_OF_UNITY_MONT)) * R_INV % Q
assert pow(root, 1 << 32, Q) == 1 and pow(root, 1 << 31, Q) == Q - 1
g3 = pow(root, 1 << 24, Q)
keys, acc = [], 1
for _ in range(256):
    keys.append((acc * R % Q) & 0xFFFFFFFF)  # low 32 bits of the Montgomery form
    acc = acc * g3 % Q
assert acc == 1 and len(set(keys)) == 256

if len(sys.argv) > 1:
    m = int(sys.argv[1], 0)
    hashes = [((k * m) & 0xFFFFFFFF) >> (32 - SQRT_HASH_BITS) for k in keys]
    ok = len(set(hashes)) == 256
    print(f"hash_mul {m:#010x}: {'perfect' if ok else 'COLLISION'} at {SQRT_HASH_BITS} bits")
    sys.exit(0 if ok else 1)

print("/* generated by keys.py */")
print("static const unsigned int K[256] = {" + ", ".join(f"{k:#010x}u" for k in keys) + "};")
